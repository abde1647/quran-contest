import {initializeTestEnvironment, assertSucceeds, assertFails} from '@firebase/rules-unit-testing';
import {doc,getDoc,setDoc,updateDoc,deleteDoc,collection,getDocs,query,where,writeBatch,serverTimestamp,addDoc} from 'firebase/firestore';
import fs from 'fs'; import test from 'node:test';
const env=await initializeTestEnvironment({projectId:'demo-quran',firestore:{rules:fs.readFileSync(new URL('../firestore.rules', import.meta.url),'utf8'),host:'127.0.0.1',port:8080}});
const A='الرابعة ابتدائي',B='الخامسة ابتدائي';
const st=(uid,section,extra={})=>({section,name:'تلميذ',hifz:5,tilawa:6,order:1,updatedAt:serverTimestamp(),updatedBy:uid,updatedByName:'x',...extra});
const db=uid=>env.authenticatedContext(uid).firestore();
const anon=()=>env.unauthenticatedContext().firestore();
let n=0;const ok=(name,p)=>test(name,()=>assertSucceeds(p()));const no=(name,p)=>test(name,()=>assertFails(p()));

await env.clearFirestore();
const DEFAULT=['الرابعة ابتدائي','الخامسة ابتدائي','الأولى متوسط','الثانية متوسط','الثالثة متوسط','الرابعة متوسط','الأولى ثانوي','قسم القرآن'];
await env.withSecurityRulesDisabled(c=>setDoc(doc(c.firestore(),'config/sections'),{list:DEFAULT}));
// bootstrap admin
test('anyone can see whether setup is done', ()=>assertSucceeds(getDoc(doc(anon(),'config/admin'))));
test('intruder cannot make himself admin without config lock', ()=>assertFails(setDoc(doc(db('x'),'users/x'),{role:'admin',active:true})));
test('first admin bootstrap succeeds', async()=>{const d=db('adm');const b=writeBatch(d);
  b.set(doc(d,'users/adm'),{role:'admin',active:true,name:'المسؤول',username:'admin'});b.set(doc(d,'config/admin'),{uid:'adm'});await assertSucceeds(b.commit())});
test('second admin bootstrap is refused', async()=>{const d=db('evil');const b=writeBatch(d);
  b.set(doc(d,'users/evil'),{role:'admin',active:true});b.set(doc(d,'config/admin'),{uid:'evil'});await assertFails(b.commit())});
ok('admin creates teacher A',()=>setDoc(doc(db('adm'),'users/tA'),{role:'teacher',active:true,section:A,name:'أستاذ أ',username:'ta'}));
ok('admin creates teacher B',()=>setDoc(doc(db('adm'),'users/tB'),{role:'teacher',active:true,section:B,name:'أستاذ ب',username:'tb'}));
no('teacher cannot create users',()=>setDoc(doc(db('tA'),'users/z'),{role:'teacher',active:true,section:A}));
no('teacher cannot promote himself',()=>updateDoc(doc(db('tA'),'users/tA'),{role:'admin'}));
no('teacher cannot change own section',()=>updateDoc(doc(db('tA'),'users/tA'),{section:B}));
ok('teacher reads own profile',()=>getDoc(doc(db('tA'),'users/tA')));
no('teacher cannot read other profile',()=>getDoc(doc(db('tA'),'users/tB')));
no('teacher cannot list users',()=>getDocs(collection(db('tA'),'users')));
ok('admin seeds student in A',()=>setDoc(doc(db('adm'),'students/s1'),st('adm',A)));
ok('admin seeds student in B',()=>setDoc(doc(db('adm'),'students/s2'),st('adm',B)));
ok('teacher A queries own section',()=>getDocs(query(collection(db('tA'),'students'),where('section','==',A))));
no('teacher A queries section B',()=>getDocs(query(collection(db('tA'),'students'),where('section','==',B))));
no('teacher A lists all students',()=>getDocs(collection(db('tA'),'students')));
no('teacher A reads B student directly',()=>getDoc(doc(db('tA'),'students/s2')));
ok('teacher A updates marks in A',()=>setDoc(doc(db('tA'),'students/s1'),st('tA',A,{hifz:9})));
no('teacher A updates B student',()=>setDoc(doc(db('tA'),'students/s2'),st('tA',B,{hifz:9})));
no('teacher A moves student to B',()=>setDoc(doc(db('tA'),'students/s1'),st('tA',B)));
no('teacher A writes mark 15',()=>setDoc(doc(db('tA'),'students/s1'),st('tA',A,{hifz:15})));
no('teacher A forges updatedBy',()=>setDoc(doc(db('tA'),'students/s1'),st('tB',A)));
ok('teacher A adds student in A',()=>setDoc(doc(db('tA'),'students/s3'),st('tA',A)));
no('teacher A adds student in B',()=>setDoc(doc(db('tA'),'students/s4'),st('tA',B)));
no('teacher cannot delete',()=>deleteDoc(doc(db('tA'),'students/s1')));
no('teacher cannot read settings',()=>getDoc(doc(db('tA'),'settings/certificate')));
ok('admin writes settings',()=>setDoc(doc(db('adm'),'settings/certificate'),{org:'x'}));
ok('teacher logs own edit',()=>addDoc(collection(db('tA'),'activity'),{uid:'tA',section:A,action:'edit',at:serverTimestamp()}));
no('teacher logs for other section',()=>addDoc(collection(db('tA'),'activity'),{uid:'tA',section:B,action:'edit',at:serverTimestamp()}));
no('teacher cannot read activity',()=>getDocs(collection(db('tA'),'activity')));
ok('admin reads activity',()=>getDocs(collection(db('adm'),'activity')));
ok('admin reads all students',()=>getDocs(collection(db('adm'),'students')));
ok('admin deletes student',()=>deleteDoc(doc(db('adm'),'students/s3')));
no('anonymous cannot read students',()=>getDocs(query(collection(anon(),'students'),where('section','==',A))));
no('anonymous cannot list logins',()=>getDocs(collection(anon(),'logins')));
ok('admin writes login card',()=>setDoc(doc(db('adm'),'logins/ta'),{email:'ta@x.app'}));
ok('anonymous gets one login card',()=>getDoc(doc(anon(),'logins/ta')));
no('teacher cannot write login cards',()=>setDoc(doc(db('tA'),'logins/ta'),{email:'evil@x.app'}));
ok('admin deactivates teacher B',()=>updateDoc(doc(db('adm'),'users/tB'),{active:false}));
no('deactivated teacher B loses access',()=>getDocs(query(collection(db('tB'),'students'),where('section','==',B))));
ok('teacher reads section list',()=>getDoc(doc(db('tA'),'config/sections')));
no('anonymous cannot read section list',()=>getDoc(doc(anon(),'config/sections')));
no('teacher cannot change section list',()=>setDoc(doc(db('tA'),'config/sections'),{list:['x']}));
no('admin cannot empty the section list',()=>setDoc(doc(db('adm'),'config/sections'),{list:[]}));
no('student in an unlisted section rejected',()=>setDoc(doc(db('adm'),'students/n1'),st('adm','قسم جديد')));
ok('admin adds a section',()=>setDoc(doc(db('adm'),'config/sections'),{list:[...DEFAULT,'قسم جديد']}));
ok('student in the new section accepted',()=>setDoc(doc(db('adm'),'students/n1'),st('adm','قسم جديد')));
ok('admin assigns teacher to the new section',()=>setDoc(doc(db('adm'),'users/tN'),{role:'teacher',active:true,section:'قسم جديد',name:'ن',username:'tn'}));
ok('new-section teacher edits own student',()=>setDoc(doc(db('tN'),'students/n1'),st('tN','قسم جديد',{hifz:8})));
no('new-section teacher cannot read section A',()=>getDocs(query(collection(db('tN'),'students'),where('section','==',A))));
no('unknown collection blocked',()=>setDoc(doc(db('adm'),'other/x'),{a:1}));
test.after(()=>env.cleanup());
